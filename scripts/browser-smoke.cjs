const assert = require('node:assert/strict');
const {go,logout}=require('./browser-navigation.cjs');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('playwright');

const base = process.env.APP_URL || 'http://127.0.0.1:18080';
const browserPath = process.env.EDGE_PATH || 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const artifacts = path.join(__dirname, '..', 'target', 'verification');
const run = async () => {
  fs.mkdirSync(artifacts, {recursive:true});
  const browser = await chromium.launch({executablePath:browserPath,headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:900},locale:'zh-CN'});
  const page = await context.newPage();
  const errors=[];
  const suffix=Date.now(),agentName='Browser QA '+suffix,username='browser_member_'+suffix,email=username+'@example.com';
  page.on('pageerror',error=>errors.push(error.message));
  try {
    await page.goto(base);
    await page.getByRole('heading',{name:'欢迎回来'}).waitFor();
    await page.locator('#auth-form [name=username]').fill('demo_admin');
    await page.locator('#auth-form [name=password]').fill('DemoOnly_2026!');
    await page.getByRole('button',{name:'登录工作台'}).click();
    await page.getByRole('heading',{name:'工作台'}).waitFor();
    await page.locator('#environment-banner').getByText('模拟模式 ·', {exact:false}).waitFor();
    await page.locator('.cards .card').first().waitFor();
    await page.screenshot({path:path.join(artifacts,'desktop.png'),fullPage:true});
    await go(page,'agents');
    await page.getByRole('button',{name:'创建智能体'}).first().click();
    await page.locator('#modal [name=name]').fill(agentName);
    await page.locator('#modal [name=description]').fill('浏览器验收智能体');
    await page.locator('#modal [name=systemPrompt]').fill('清晰回答');
    await page.locator('#modal [name=modelName]').fill('demo-model');
    await page.locator('#modal [name=status]').selectOption('ACTIVE');
    await page.locator('#modal button[type=submit]').click();
    await page.getByRole('heading',{name:agentName,exact:true}).waitFor();
    await go(page,'tasks');
    await page.locator('#primary-action').click();
    await page.locator('#modal [name=agentId]').selectOption({label:agentName+' · demo-model'});
    await page.locator('#modal [name=input]').fill('请介绍这个项目');
    assert.equal(await page.locator('#modal [name=enqueue]').isChecked(),true);
    await page.locator('#modal button[type=submit]').click();
    await page.locator('tbody tr').filter({hasText:'请介绍这个项目'}).getByRole('button',{name:'查看详情'}).click();
    await page.locator('#modal .badge.SUCCEEDED').waitFor({timeout:15000});
    await page.getByText('【演示响应').waitFor();
    await page.locator('#modal-close').click();
    await logout(page);
    await page.locator('#auth-switch').click();
    await page.locator('#auth-form [name=username]').fill(username);
    await page.locator('#auth-form [name=email]').fill(email);
    await page.locator('#auth-form [name=password]').fill('browser-pass-2026');
    await page.locator('#auth-form').getByRole('button',{name:'创建账号'}).click();
    await page.getByRole('heading',{name:'工作台'}).waitFor();
    assert.equal(await page.locator('nav [data-page=users]').isVisible(),false);
    const token=await page.evaluate(()=>sessionStorage.getItem('agent-token'));
    const forbidden=await page.request.get(base+'/api/admin/users',{headers:{Authorization:'Bearer '+token}});
    assert.equal(forbidden.status(),403);
    await go(page,'tasks');
    await page.locator('#primary-action').click();
    await page.locator('#modal [name=agentId]').selectOption({label:agentName+' · demo-model'});
    await page.locator('#modal [name=input]').fill('<img src=x onerror=window.__xss=1>');
    await page.locator('#modal button[type=submit]').click();
    await page.locator('tbody tr').filter({hasText:'<img src=x'}).getByRole('button',{name:'查看详情'}).click();
    await page.locator('#modal pre').first().getByText('<img src=x onerror=window.__xss=1>').waitFor();
    assert.equal(await page.evaluate(()=>window.__xss),undefined);
    await page.locator('#modal-close').click();
    await logout(page);
    await page.locator('#auth-form [name=username]').fill('demo_admin');
    await page.locator('#auth-form [name=password]').fill('DemoOnly_2026!');
    await page.getByRole('button',{name:'登录工作台'}).click();
    await go(page,'users');
    await page.getByText(email,{exact:true}).waitFor();
    await go(page,'audit');
    await page.getByText('创建任务').first().waitFor();
    await page.setViewportSize({width:390,height:844});
    await go(page,'overview');
    await page.locator('#toast').waitFor({state:'hidden'});
    await page.screenshot({path:path.join(artifacts,'mobile.png'),fullPage:true});
    assert.deepEqual(errors,[]);
    console.log('Browser smoke passed: login, CRUD, queue, result, registration, roles, audit, XSS rendering, desktop/mobile.');
  } finally {await browser.close();}
};
run().catch(error=>{console.error(error);process.exitCode=1;});
