-- PostgreSQL: supports both a new database and the previous Hibernate-managed schema.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL, email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL, role VARCHAR(255) NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_users_username ON users(username);
CREATE UNIQUE INDEX IF NOT EXISTS uk_users_email ON users(email);
CREATE TABLE IF NOT EXISTS agents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_name VARCHAR(100) NOT NULL, description VARCHAR(500),
    system_prompt TEXT NOT NULL, model_name VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL,
    creator_id BIGINT NOT NULL REFERENCES users(id),
    create_time TIMESTAMP WITH TIME ZONE NOT NULL, update_time TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id BIGINT NOT NULL REFERENCES agents(id), user_id BIGINT NOT NULL REFERENCES users(id),
    input TEXT NOT NULL, output TEXT, status VARCHAR(20) NOT NULL,
    execution_model VARCHAR(100), execution_prompt TEXT,
    create_time TIMESTAMP WITH TIME ZONE NOT NULL, update_time TIMESTAMP WITH TIME ZONE NOT NULL
);
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS execution_model VARCHAR(100);
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS execution_prompt TEXT;
ALTER TABLE tasks ADD CONSTRAINT ck_tasks_status
    CHECK (status IN ('PENDING','QUEUED','RUNNING','SUCCEEDED','FAILED','CANCELLED'));
CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(100) NOT NULL, action VARCHAR(80) NOT NULL,
    resource_type VARCHAR(40) NOT NULL, resource_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_tasks_queue ON tasks(status, create_time, id);
CREATE INDEX IF NOT EXISTS ix_tasks_user ON tasks(user_id, create_time);
CREATE INDEX IF NOT EXISTS ix_tasks_agent ON tasks(agent_id);
CREATE INDEX IF NOT EXISTS ix_agents_creator ON agents(creator_id);
CREATE INDEX IF NOT EXISTS ix_audit_recent ON audit_events(created_at DESC, id DESC);

CREATE TABLE model_settings (
    id BIGINT PRIMARY KEY, version BIGINT NOT NULL, mode VARCHAR(10) NOT NULL,
    base_url VARCHAR(1000) NOT NULL, encrypted_key TEXT,
    default_model VARCHAR(100) NOT NULL, timeout_seconds INTEGER NOT NULL
);
CREATE TABLE skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL, description VARCHAR(500), instructions TEXT NOT NULL,
    enabled BOOLEAN NOT NULL, owner_id BIGINT NOT NULL REFERENCES users(id), updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE agent_skills (
    agent_id BIGINT NOT NULL REFERENCES agents(id), skill_id BIGINT NOT NULL REFERENCES skills(id),
    position INTEGER NOT NULL, PRIMARY KEY (agent_id, position)
);
CREATE INDEX ix_skills_owner ON skills(owner_id);
CREATE INDEX ix_agent_skills_skill ON agent_skills(skill_id);
ALTER TABLE tasks ADD COLUMN execution_mode VARCHAR(10);
ALTER TABLE tasks ADD COLUMN provider_revision BIGINT;
ALTER TABLE tasks ADD COLUMN execution_timeout_seconds INTEGER;
ALTER TABLE tasks ADD COLUMN execution_skills TEXT;

CREATE TABLE chat_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id), agent_id BIGINT NOT NULL REFERENCES agents(id),
    title VARCHAR(100) NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_chat_sessions_owner ON chat_sessions(owner_id, updated_at DESC);
CREATE TABLE chat_turns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES chat_sessions(id), request_id VARCHAR(36) NOT NULL,
    input TEXT NOT NULL, output TEXT, error VARCHAR(500), status VARCHAR(20) NOT NULL,
    model VARCHAR(100) NOT NULL, mode VARCHAR(10) NOT NULL, skills TEXT NOT NULL,
    context_turns INTEGER NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL, deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(session_id, request_id), CHECK(status IN ('RUNNING','SUCCEEDED','FAILED'))
);
CREATE INDEX ix_chat_turns_session ON chat_turns(session_id, id);
