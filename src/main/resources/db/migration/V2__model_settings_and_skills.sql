CREATE TABLE model_settings (
    id BIGINT PRIMARY KEY, version BIGINT NOT NULL, mode VARCHAR(10) NOT NULL,
    base_url VARCHAR(1000) NOT NULL, encrypted_key TEXT,
    default_model VARCHAR(100) NOT NULL, timeout_seconds INTEGER NOT NULL
);
CREATE TABLE skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL, description VARCHAR(500), instructions TEXT NOT NULL,
    enabled BOOLEAN NOT NULL, owner_id BIGINT NOT NULL REFERENCES users(id), updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE agent_skills (
    agent_id BIGINT NOT NULL REFERENCES agents(id), skill_id BIGINT NOT NULL REFERENCES skills(id),
    position INTEGER NOT NULL, PRIMARY KEY (agent_id, position)
);
CREATE INDEX ix_skills_owner ON skills(owner_id);
CREATE INDEX ix_agent_skills_skill ON agent_skills(skill_id);
