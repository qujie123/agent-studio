ALTER TABLE agents ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
CREATE TABLE usage_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key VARCHAR(80) NOT NULL UNIQUE, kind VARCHAR(10) NOT NULL, source_id BIGINT,
    user_id BIGINT NOT NULL, model VARCHAR(100) NOT NULL, mode VARCHAR(10) NOT NULL,
    status VARCHAR(20) NOT NULL, input_tokens BIGINT, output_tokens BIGINT,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL, finished_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_usage_user_time ON usage_records(user_id,recorded_at DESC,id DESC);
-- Old task execution start times were not retained; update_time is the best available historical timestamp.
INSERT INTO usage_records(source_key,kind,source_id,user_id,model,mode,status,input_tokens,output_tokens,recorded_at,finished_at)
SELECT 'TASK:' || CAST(id AS VARCHAR),'TASK',id,user_id,execution_model,execution_mode,status,input_tokens,output_tokens,update_time,
    CASE WHEN status IN ('SUCCEEDED','FAILED') THEN update_time ELSE NULL END
FROM tasks WHERE execution_mode IS NOT NULL AND execution_model IS NOT NULL AND status IN ('RUNNING','SUCCEEDED','FAILED');
