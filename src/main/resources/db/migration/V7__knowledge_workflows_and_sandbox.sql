CREATE TABLE knowledge_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(100) NOT NULL,
    content TEXT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_knowledge_owner_time ON knowledge_documents(owner_id,updated_at DESC,id DESC);
CREATE TABLE agent_knowledge (
    agent_id BIGINT NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    document_id BIGINT NOT NULL REFERENCES knowledge_documents(id),
    position INTEGER NOT NULL,
    PRIMARY KEY(agent_id,document_id),
    UNIQUE(agent_id,position)
);
ALTER TABLE tasks ADD COLUMN execution_knowledge TEXT;
ALTER TABLE chat_turns ADD COLUMN knowledge TEXT;
ALTER TABLE skills ADD COLUMN kind VARCHAR(20) NOT NULL DEFAULT 'PROMPT';
ALTER TABLE skills ADD COLUMN code TEXT;
CREATE TABLE workflows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(100) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    definition TEXT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_workflow_owner_time ON workflows(owner_id,updated_at DESC,id DESC);
CREATE TABLE workflow_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id BIGINT NOT NULL REFERENCES workflows(id),
    owner_id BIGINT NOT NULL REFERENCES users(id),
    request_id VARCHAR(36) NOT NULL,
    input TEXT NOT NULL,
    output TEXT,
    error VARCHAR(500),
    status VARCHAR(20) NOT NULL,
    definition TEXT NOT NULL,
    steps TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(workflow_id,request_id)
);
CREATE INDEX ix_workflow_run_owner ON workflow_runs(owner_id,created_at DESC,id DESC);
CREATE TABLE skill_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id BIGINT REFERENCES skills(id) ON DELETE SET NULL,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    request_id VARCHAR(36) NOT NULL,
    skill_name VARCHAR(100) NOT NULL,
    skill_version BIGINT NOT NULL,
    code TEXT NOT NULL,
    input TEXT NOT NULL,
    output TEXT,
    error VARCHAR(500),
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(owner_id,request_id)
);
CREATE INDEX ix_skill_run_owner ON skill_runs(owner_id,created_at DESC,id DESC);
